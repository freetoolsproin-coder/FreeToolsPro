export function categoryFromPath(pathname) {
  if (!pathname) return null;
  for (const [prefix, category] of PATH_PREFIXES) {
    if (pathname.startsWith(prefix) || pathname === prefix.slice(0, -1)) {
      return category;
    }
  }
  return null;
}
