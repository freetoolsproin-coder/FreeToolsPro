const wiki = (t) => `https://en.wikipedia.org/wiki/${encodeURIComponent(t.replace(/ /g, "_")).replace(/%2C/g, ",").replace(/%2F/g, "/").replace(/%27/g, "'").replace(/%28/g, "(").replace(/%29/g, ")")}`;

/** schema.org Thing nodes for a tool, or [] when none is mapped. */
export function entitiesFor(id) {
  return (TOOL[id] || "").split(" ").filter(Boolean).map((k) => {
    const [name, q] = E[k];
    return { "@type": "Thing", name, sameAs: [wiki(name), ...(q ? [`https://www.wikidata.org/wiki/${q}`] : [])] };
  });
}

export const ENTITY_KEYS_OK = () => Object.values(TOOL).every((v) => v.split(" ").every((k) => E[k]));
