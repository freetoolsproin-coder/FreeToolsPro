/** Icon for one tool. Falls back to its category's icon, then a briefcase. */
export function ToolIcon({ tool, size = 20, className }) {
  const Icon = TOOL_ICONS[tool.id] || CATEGORY_ICONS[tool.cat] || Briefcase;
  return <Icon size={size} strokeWidth={1.8} aria-hidden="true" className={className} />;
}

export function CategoryIcon({ id, size = 18, className }) {
  const Icon = CATEGORY_ICONS[id] || Briefcase;
  return <Icon size={size} strokeWidth={1.8} aria-hidden="true" className={className} />;
}

