// After `astro build`: write host redirect files into dist/ so retired URLs return a real 301,
// and the deleted blog returns 410 Gone.
import { writeFileSync, existsSync } from "node:fs";
import { REDIRECTS, WILDCARD_REDIRECTS, FILE_REDIRECTS, GONE } from "../src/data/redirects.js";

if (!existsSync("dist")) throw new Error("Run after astro build (dist/ not found).");
const pairs = [...Object.entries(REDIRECTS), ...Object.entries(FILE_REDIRECTS)];

// Netlify and Cloudflare Pages
const lines = [
  ...GONE.exact.map((p) => `${p} /404.html 410`),
  ...GONE.prefixes.map((p) => `${p}* /404.html 410`),
  ...pairs.map(([f, t]) => `${f} ${t} 301`),
  ...WILDCARD_REDIRECTS.map(([f, t]) => `${f} ${t} 301`),
];
writeFileSync("dist/_redirects", lines.join("\n") + "\n");

// Vercel (it has no 410 status; the deleted blog URLs fall through to the 404 page there)
writeFileSync(
  "dist/vercel.json",
  JSON.stringify(
    {
      cleanUrls: true,
      trailingSlash: false,
      redirects: [...pairs.map(([s, d]) => ({ source: s, destination: d, permanent: true })), ...WILDCARD_REDIRECTS.map(([s, d]) => ({ source: s.replace("/*", "/:variant"), destination: d, permanent: true }))],
    },
    null,
    2
  )
);

// Node server (server.mjs) and anything else that wants plain data
writeFileSync("dist/redirects.json", JSON.stringify({ exact: Object.fromEntries(pairs), prefixes: WILDCARD_REDIRECTS.map(([f, t]) => [f.slice(0, -1), t]), gone: GONE }, null, 2));

// nginx: included from the server block (see deploy/nginx.conf). Exact matches win over everything else.
const ngx = [
  "# Generated by scripts/write-redirects.mjs. Do not edit; rebuild instead.",
  ...GONE.exact.map((p) => `location = ${p} { return 410; }`),
  ...GONE.prefixes.map((p) => `location ^~ ${p} { return 410; }`),
  ...pairs.map(([f, t]) => `location = ${f} { return 301 ${t}$is_args$args; }`),
  ...WILDCARD_REDIRECTS.map(([f, t]) => `location ^~ ${f.slice(0, -1)} { return 301 ${t}; }`),
];
writeFileSync("dist/nginx-redirects.conf", ngx.join("\n") + "\n");

// Apache / LiteSpeed (shared hosting): only used if the host reads .htaccess; nginx ignores it.
const esc = (p) => p.replace(/^\//, "").replace(/[.+?()[\]{}|^$\\]/g, "\\$&");
const ht = [
  "# Generated by scripts/write-redirects.mjs. Do not edit; rebuild instead.",
  "RewriteEngine On",
  "RewriteBase /",
  "Options -MultiViews",
  "RewriteCond %{HTTP_HOST} ^www\\.freetoolspro\\.in$ [NC]",
  "RewriteRule ^ https://freetoolspro.in%{REQUEST_URI} [R=301,L]",
  "# Deleted blog: 410 Gone",
  `RewriteCond %{HTTP_HOST} ^${GONE.host.replace(/\./g, "\\.")}$ [NC]`,
  "RewriteRule ^ - [G]",
  ...GONE.exact.map((p) => `RewriteRule ^${esc(p)}/?$ - [G]`),
  ...GONE.prefixes.map((p) => `RewriteRule ^${esc(p)} - [G]`),
  "# Retired URLs on the main site",
  ...pairs.map(([f, t]) => `RewriteRule ^${esc(f)}/?$ ${t} [R=301,L]`),
  ...WILDCARD_REDIRECTS.map(([f, t]) => `RewriteRule ^${esc(f.slice(0, -2))}/.+$ ${t} [R=301,L]`),
  "# One URL per page: /page/ -> /page",
  "RewriteCond %{REQUEST_FILENAME} !-d",
  "RewriteRule ^(.+)/$ /$1 [R=301,L]",
  "# Pages are built as /x/y.html but linked without .html",
  "RewriteCond %{REQUEST_FILENAME} !-f",
  "RewriteCond %{REQUEST_FILENAME}.html -f",
  "RewriteRule ^(.+)$ $1.html [L]",
  "ErrorDocument 404 /404.html",
  "ErrorDocument 410 /404.html",
];
writeFileSync("dist/.htaccess", ht.join("\n") + "\n");

console.log(`Wrote ${pairs.length} redirects (+${WILDCARD_REDIRECTS.length} wildcard) and the blog 410 rules to dist/_redirects, dist/vercel.json, dist/redirects.json, dist/nginx-redirects.conf, dist/.htaccess`);
